-- Versão 2: bloqueio temporário de login após tentativas repetidas.
-- Guarda apenas falhas; um login bem-sucedido apaga as falhas do identificador.
CREATE TABLE tentativas_login (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identificador varchar(260) NOT NULL, -- 'email:<e-mail>' ou 'cpf:<11 dígitos>'
  ip            varchar(64), -- texto livre: o header x-forwarded-for pode vir malformado
  criado_em     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_tentativas_login_identificador ON tentativas_login (identificador, criado_em);

