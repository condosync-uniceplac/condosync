-- =============================================================
-- CondoSync - esquema inicial
-- Conversão fiel de db/condosync_schema.dbml para PostgreSQL 16.
-- Executado pelo scripts/migrate.js dentro de uma transação e registrado
-- em schema_migrations (não roda duas vezes).
