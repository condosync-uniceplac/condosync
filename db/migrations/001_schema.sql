CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS btree_gist;
-- gen_random_uuid() é nativo a partir do PostgreSQL 13

-- -------------------------------------------------------------
-- Enums
-- -------------------------------------------------------------
CREATE TYPE perfil_acesso    AS ENUM ('MORADOR', 'PORTARIA', 'SINDICO', 'ADMIN');
CREATE TYPE tipo_termo       AS ENUM ('TERMOS_USO', 'POLITICA_PRIVACIDADE');
CREATE TYPE status_reserva   AS ENUM ('PENDENTE', 'CONFIRMADA', 'CANCELADA', 'CONCLUIDA');
CREATE TYPE tipo_documento   AS ENUM ('RG', 'CPF', 'CNPJ', 'OUTRO');
CREATE TYPE status_visita    AS ENUM ('AGUARDANDO', 'AUTORIZADO', 'PRESENTE', 'FINALIZADO', 'CANCELADO');
CREATE TYPE prioridade_aviso AS ENUM ('NORMAL', 'URGENTE');
CREATE TYPE urgencia_chamado AS ENUM ('BAIXA', 'MEDIA', 'ALTA');
CREATE TYPE status_chamado   AS ENUM ('ABERTO', 'EM_ANALISE', 'RESOLVIDO');

-- -------------------------------------------------------------
-- Estrutura do condomínio
-- -------------------------------------------------------------
CREATE TABLE condominios (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       varchar(150) NOT NULL,
  cnpj       char(14) UNIQUE CHECK (cnpj ~ '^\d{14}$'),
  cep        char(8) CHECK (cep ~ '^\d{8}$'),
  logradouro varchar(200),
  numero     varchar(10),
  bairro     varchar(100),
  cidade     varchar(100),
  uf         char(2),
  criado_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE blocos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  condominio_id bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  nome          varchar(50) NOT NULL,
  UNIQUE (condominio_id, nome)
);

CREATE TABLE unidades (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bloco_id bigint NOT NULL REFERENCES blocos (id) ON DELETE CASCADE,
  numero   varchar(20) NOT NULL,
  UNIQUE (bloco_id, numero)
);
CREATE INDEX ix_unidades_bloco ON unidades (bloco_id);

-- -------------------------------------------------------------
-- Usuários, vínculos e termos
-- -------------------------------------------------------------
CREATE TABLE usuarios (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_completo   varchar(150) NOT NULL,
  email           citext NOT NULL UNIQUE,
  telefone        varchar(20) NOT NULL,
  cpf             char(11) NOT NULL UNIQUE CHECK (cpf ~ '^\d{11}$'),
  rg              varchar(20),
  data_nascimento date NOT NULL CHECK (data_nascimento <= current_date),
  senha_hash      text NOT NULL,
  ativo           boolean NOT NULL DEFAULT true,
  criado_em       timestamptz NOT NULL DEFAULT now(),
  atualizado_em   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE vinculos_condominio (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id    bigint NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  condominio_id bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  perfil        perfil_acesso NOT NULL,
  unidade_id    bigint REFERENCES unidades (id),
  ativo         boolean NOT NULL DEFAULT true,
  criado_em     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_morador_tem_unidade CHECK (perfil <> 'MORADOR' OR unidade_id IS NOT NULL),
  UNIQUE (usuario_id, condominio_id, perfil, unidade_id)
);
CREATE INDEX ix_vinculos_condominio ON vinculos_condominio (condominio_id, perfil);
CREATE INDEX ix_vinculos_unidade ON vinculos_condominio (unidade_id);

CREATE TABLE termos_documentos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo          tipo_termo NOT NULL,
  versao        varchar(20) NOT NULL,
  conteudo      text NOT NULL,
  vigente_desde timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tipo, versao)
);

CREATE TABLE aceites_termos (
  usuario_id bigint NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  termo_id   bigint NOT NULL REFERENCES termos_documentos (id),
  aceito_em  timestamptz NOT NULL DEFAULT now(),
  ip         inet,
  PRIMARY KEY (usuario_id, termo_id)
);

CREATE TABLE recuperacoes_senha (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id bigint NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expira_em  timestamptz NOT NULL,
  usado_em   timestamptz,
  criado_em  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_recuperacao_usuario ON recuperacoes_senha (usuario_id);

-- -------------------------------------------------------------
-- Reservas de áreas comuns
-- -------------------------------------------------------------
CREATE TABLE espacos (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  condominio_id      bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  nome               varchar(100) NOT NULL,
  descricao          text,
  capacidade_pessoas integer NOT NULL CHECK (capacidade_pessoas > 0),
  valor              numeric(10, 2) NOT NULL DEFAULT 0 CHECK (valor >= 0),
  ativo              boolean NOT NULL DEFAULT true,
  UNIQUE (condominio_id, nome)
);

CREATE TABLE reservas (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  espaco_id     bigint NOT NULL REFERENCES espacos (id),
  vinculo_id    bigint NOT NULL REFERENCES vinculos_condominio (id),
  inicio        timestamptz NOT NULL,
  fim           timestamptz NOT NULL,
  status        status_reserva NOT NULL DEFAULT 'PENDENTE',
  valor_cobrado numeric(10, 2) NOT NULL DEFAULT 0 CHECK (valor_cobrado >= 0),
  criado_em     timestamptz NOT NULL DEFAULT now(),
  CHECK (fim > inicio)
);
CREATE INDEX ix_reservas_vinculo ON reservas (vinculo_id, inicio);
CREATE INDEX ix_reservas_espaco_ini ON reservas (espaco_id, inicio);

-- -------------------------------------------------------------
-- Portaria: visitantes e visitas
-- -------------------------------------------------------------
CREATE TABLE visitantes (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  condominio_id  bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  nome           varchar(150) NOT NULL,
  tipo_documento tipo_documento NOT NULL,
  documento      varchar(20) NOT NULL,
  criado_em      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (condominio_id, tipo_documento, documento)
);

CREATE TABLE visitas (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitante_id      bigint NOT NULL REFERENCES visitantes (id),
  unidade_id        bigint NOT NULL REFERENCES unidades (id),
  autorizado_por_id bigint REFERENCES vinculos_condominio (id),
  registrada_por_id bigint REFERENCES vinculos_condominio (id),
  placa_veiculo     varchar(8),
  previsao_entrada  timestamptz,
  entrada_em        timestamptz,
  saida_em          timestamptz,
  status            status_visita NOT NULL DEFAULT 'AGUARDANDO',
  codigo_convite    uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  criado_em         timestamptz NOT NULL DEFAULT now(),
  CHECK (saida_em IS NULL OR (entrada_em IS NOT NULL AND saida_em >= entrada_em)),
  CHECK (status NOT IN ('PRESENTE', 'FINALIZADO') OR entrada_em IS NOT NULL),
  CHECK (status <> 'FINALIZADO' OR saida_em IS NOT NULL),
  CHECK (status NOT IN ('AUTORIZADO', 'PRESENTE', 'FINALIZADO') OR autorizado_por_id IS NOT NULL)
);
CREATE INDEX ix_visitas_unidade ON visitas (unidade_id, criado_em);
CREATE INDEX ix_visitas_visitante ON visitas (visitante_id);
CREATE INDEX ix_visitas_ativas ON visitas (status, previsao_entrada);

-- -------------------------------------------------------------
-- Mural de avisos
-- -------------------------------------------------------------
CREATE TABLE categorias_aviso (
  id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(50) NOT NULL UNIQUE
);

CREATE TABLE avisos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  condominio_id bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  categoria_id  smallint NOT NULL REFERENCES categorias_aviso (id),
  autor_id      bigint NOT NULL REFERENCES vinculos_condominio (id),
  titulo        varchar(200) NOT NULL,
  corpo         text NOT NULL,
  prioridade    prioridade_aviso NOT NULL DEFAULT 'NORMAL',
  publicado_em  timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_avisos_mural ON avisos (condominio_id, publicado_em);
CREATE INDEX ix_avisos_categoria ON avisos (categoria_id);

CREATE TABLE anexos_aviso (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aviso_id      bigint NOT NULL REFERENCES avisos (id) ON DELETE CASCADE,
  nome_arquivo  varchar(255) NOT NULL,
  storage_path  text NOT NULL,
  mime_type     varchar(100) NOT NULL,
  tamanho_bytes bigint NOT NULL CHECK (tamanho_bytes >= 0)
);
CREATE INDEX ix_anexos_aviso ON anexos_aviso (aviso_id);

CREATE TABLE aviso_leituras (
  aviso_id   bigint NOT NULL REFERENCES avisos (id) ON DELETE CASCADE,
  usuario_id bigint NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  lido_em    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (aviso_id, usuario_id)
);
CREATE INDEX ix_leituras_usuario ON aviso_leituras (usuario_id);

-- -------------------------------------------------------------
-- Chamados / ocorrências
-- -------------------------------------------------------------
CREATE TABLE categorias_chamado (
  id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(50) NOT NULL UNIQUE
);

CREATE TABLE chamados (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  condominio_id  bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  solicitante_id bigint NOT NULL REFERENCES vinculos_condominio (id),
  unidade_id     bigint REFERENCES unidades (id),
  categoria_id   smallint NOT NULL REFERENCES categorias_chamado (id),
  urgencia       urgencia_chamado NOT NULL DEFAULT 'MEDIA',
  titulo         varchar(200) NOT NULL,
  descricao      text NOT NULL,
  status         status_chamado NOT NULL DEFAULT 'ABERTO',
  criado_em      timestamptz NOT NULL DEFAULT now(),
  atualizado_em  timestamptz NOT NULL DEFAULT now(),
  resolvido_em   timestamptz,
  CHECK ((status = 'RESOLVIDO') = (resolvido_em IS NOT NULL))
);
CREATE INDEX ix_chamados_painel ON chamados (condominio_id, status, criado_em);
CREATE INDEX ix_chamados_solicitante ON chamados (solicitante_id);

CREATE TABLE anexos_chamado (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chamado_id    bigint NOT NULL REFERENCES chamados (id) ON DELETE CASCADE,
  nome_arquivo  varchar(255) NOT NULL,
  storage_path  text NOT NULL,
  mime_type     varchar(100) NOT NULL,
  tamanho_bytes bigint NOT NULL CHECK (tamanho_bytes >= 0)
);
CREATE INDEX ix_anexos_chamado ON anexos_chamado (chamado_id);

CREATE TABLE chamado_acompanhamentos (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chamado_id  bigint NOT NULL REFERENCES chamados (id) ON DELETE CASCADE,
  autor_id    bigint NOT NULL REFERENCES vinculos_condominio (id),
  novo_status status_chamado,
  comentario  text,
  criado_em   timestamptz NOT NULL DEFAULT now(),
  CHECK (novo_status IS NOT NULL OR comentario IS NOT NULL)
);
CREATE INDEX ix_acompanh_chamado ON chamado_acompanhamentos (chamado_id, criado_em);

-- -------------------------------------------------------------
-- Enquetes / votações
-- -------------------------------------------------------------
CREATE TABLE enquetes (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  condominio_id bigint NOT NULL REFERENCES condominios (id) ON DELETE CASCADE,
  criador_id    bigint NOT NULL REFERENCES vinculos_condominio (id),
  pergunta      varchar(300) NOT NULL,
  descricao     text,
  abre_em       timestamptz NOT NULL DEFAULT now(),
  encerra_em    timestamptz NOT NULL,
  criado_em     timestamptz NOT NULL DEFAULT now(),
  CHECK (encerra_em > abre_em)
);
CREATE INDEX ix_enquetes_condominio ON enquetes (condominio_id, encerra_em);

CREATE TABLE enquete_opcoes (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquete_id bigint NOT NULL REFERENCES enquetes (id) ON DELETE CASCADE,
  texto      varchar(200) NOT NULL,
  ordem      smallint NOT NULL,
  UNIQUE (enquete_id, ordem),
  UNIQUE (id, enquete_id)
);

CREATE TABLE votos_enquete (
  enquete_id    bigint NOT NULL,
  usuario_id    bigint NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  opcao_id      bigint NOT NULL,
  votado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (enquete_id, usuario_id),
  FOREIGN KEY (opcao_id, enquete_id) REFERENCES enquete_opcoes (id, enquete_id) ON DELETE CASCADE
);
CREATE INDEX ix_votos_opcao ON votos_enquete (opcao_id);
CREATE INDEX ix_votos_usuario ON votos_enquete (usuario_id);

